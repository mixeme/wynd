export interface FixCopy {
	title: string;
	body: string;
}

const FIX_COPY: Record<string, FixCopy> = {
	proxy_client: {
		title: 'Прокси не передаёт настоящий адрес',
		body: 'Сервер видит все запросы как приходящие с 127.0.0.1: попытки ввода кода считаются на всех сразу — одному не войти, у другого код можно перебирать.'
	},
	proxy_body_limit: {
		title: 'Потолок тела запроса слишком мал',
		body: 'Прокси обрезает загрузки раньше, чем Wynd. Фотография в полном разрешении вернётся с 413. Та же вставка поднимает лимит и передаёт настоящий адрес клиента.'
	},
	proxy_headers: {
		title: 'Прокси не передаёт HTTPS',
		body: 'Без X-Forwarded-Proto: https ссылки в письмах и уведомлениях уйдут на http://. Та же вставка чинит и остальные строки прокси.'
	},
	proxy_sse: {
		title: 'Прокси буферизует ленту',
		body: 'SSE не доходит до браузера сразу — лента «застывает», пока прокси не сбросит буфер. Та же вставка отключает буферизацию.'
	},
	proxy_timeout: {
		title: 'Прокси ждёт слишком мало',
		body: 'Длинная загрузка обрывается на прокси. Во вставке ниже — 300 с на чтение ответа; вставка та же, что для остальных поломок прокси.'
	}
};

const DEFAULT_FIX: FixCopy = {
	title: 'Готовая вставка для прокси',
	body: 'Wynd не трогает ваш прокси и не перезапускает его: вставляете вы сами. Поломки прокси чинятся одной вставкой.'
};

export function fixCopy(fail: string): FixCopy {
	return FIX_COPY[fail] ?? DEFAULT_FIX;
}
