-- 0010: в sessions хранится sha256(token), а не сам токен.
--
-- В плане 42 эта миграция названа 0012, но волна 1 выходит раньше волны 2,
-- а пропуск номера в середине цепочки запрещён (MIG-1). Номера сдвинуты:
-- сессии — 0010, метки времени — 0011, client_id — 0012.
--
-- Токены лежали в БД открытым текстом, и любой бэкап содержал живые Bearer
-- на 30 дней вперёд (AUTH-4). Пересчитать существующие строки нельзя —
-- хеш необратим, — поэтому все сессии удаляются: участники и админ входят
-- заново. Колонка token переименована в token_hash, чтобы старый код не
-- смог случайно писать в неё сырой токен.

DELETE FROM sessions;

ALTER TABLE sessions RENAME COLUMN token TO token_hash;
