-- 0025: род участника в круге (план 46, A5).
--
-- Строки журнала — в прошедшем времени: «Аня вступила в круг». Род человек
-- выбирает сам при вступлении («Мужской / Женский») и меняет в «Кто вы в
-- этом круге». Не выбран — строка без глагола: «В круге: Аня». Хранится у
-- участия в круге, как имя: в разных кругах человек может быть разным.
-- Старые строки не переписываются — они хранятся готовым текстом в events.

ALTER TABLE identities ADD COLUMN gender TEXT CHECK (gender IN ('m', 'f'));
