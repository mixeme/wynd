-- 0024: битрейт звука по умолчанию — 192 кбит/с (план 46, A6).
--
-- 0023 вышла в 0.18.37 со 128. Новым установкам 0023 теперь ставит 192;
-- уже обновлённым — переводим 128 в 192. Свой битрейт, отличный от 128,
-- администратор мог задать сознательно — его не трогаем.

UPDATE instance_settings SET compress_audio_bitrate_kbps = 192 WHERE compress_audio_bitrate_kbps = 128;
